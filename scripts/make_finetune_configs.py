"""Build the two controlled fine-tuning configs from the untouched upstream reference.

Usage:  python scripts/make_finetune_configs.py

Both YAMLs are produced from the same text with the same edits. Only
`Global.epoch_num` and the two output paths differ between them, which is
what assignment item 2.4 requires. Every edit is asserted to happen exactly
once, so a changed upstream file fails loudly instead of silently.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / "configs" / "upstream_reference" / "latin_PP-OCRv5_mobile_rec.yml"
OUT_DIR = ROOT / "configs" / "ppocrv5_mobile"

# Kaggle paths (dataset is mounted read-only under /kaggle/input).
DATA_ROOT = "/kaggle/input/datasets/baonguyenngoc0902/hcmus-nlp-vietnamese-recognition-resources"
DATA_DIR = f"{DATA_ROOT}/vi_rec_100k"
DICT_PATH = f"{DATA_ROOT}/vi_dict.txt"
PRETRAINED = "/kaggle/working/pretrained/PP-OCRv5_mobile_rec_pretrained.pdparams"

# Shared by BOTH runs (not experiment variables).
MAX_TEXT_LEN = 100   # upstream 25; Vietnamese lines reach 80 chars (test max = 80)
IMG_W = 960          # upstream 320; ~120 CTC steps for lines of up to 80 chars
FIRST_BS = 24        # per-GPU batch at the smallest scale; 48 ran out of memory on a 15 GB T4 at 960 px width
SEED = 42            # PaddleOCR defaults to 1024 when Global.seed is absent
WARMUP_EPOCH = 0.5   # upstream 5 would be longer than the whole 2-epoch run


def replace_once(text, old, new):
    assert text.count(old) == 1, f"expected exactly one occurrence of {old!r}, got {text.count(old)}"
    return text.replace(old, new)


def build(epochs):
    lines = UPSTREAM.read_text(encoding="utf-8").splitlines(keepends=True)
    while lines and lines[0].startswith("#"):  # drop the reference file's own comment header
        lines.pop(0)
    t = "".join(lines)
    run = f"ppocrv5_mobile_{epochs}epochs"
    edits = [
        ("model_name: latin_PP-OCRv5_mobile_rec", "model_name: PP-OCRv5_mobile_rec"),
        ("use_gpu: true", f"use_gpu: true\n  seed: {SEED}"),
        ("print_batch_step: 10", "print_batch_step: 100"),
        ("epoch_num: 75", f"epoch_num: {epochs}"),
        ("save_model_dir: ./output/latin_rec_ppocr_v5", f"save_model_dir: /kaggle/working/output/{run}"),
        ("save_epoch_step: 10", "save_epoch_step: 1"),
        ("eval_batch_step: [0, 500]", "eval_batch_step: [0, 1000]"),
        ("pretrained_model: PP-OCRv5_mobile_rec_pretrained.pdparams", f"pretrained_model: {PRETRAINED}"),
        ("character_dict_path: ./ppocr/utils/dict/ppocrv5_latin_dict.txt", f"character_dict_path: {DICT_PATH}"),
        ("save_res_path: ./output/rec/predicts_ppocrv5.txt", f"save_res_path: /kaggle/working/output/{run}/predicts.txt"),
        ("d2s_train_image_shape: [3, 48, 320]", f"d2s_train_image_shape: [3, 48, {IMG_W}]"),
        ("warmup_epoch: 5", f"warmup_epoch: {WARMUP_EPOCH}"),
        ("image_shape: [48, 320, 3]", f"image_shape: [48, {IMG_W}, 3]"),
        ("scales: [[320, 32], [320, 48], [320, 64]]", f"scales: [[{IMG_W}, 32], [{IMG_W}, 48], [{IMG_W}, 64]]"),
        ("first_bs: &bs 128", f"first_bs: &bs {FIRST_BS}"),
        ("num_workers: 8", "num_workers: 4"),
        ("label_file_list:\n    - ./train_data/train_list.txt", f"label_file_list:\n    - {DATA_DIR}/rec_train.txt"),
        ("label_file_list:\n    - ./train_data/eval_list.txt", f"label_file_list:\n    - {DATA_DIR}/rec_val.txt"),
        ("eval_mode: True\n          image_shape: [3, 48, 320]", f"eval_mode: True\n          image_shape: [3, 48, {IMG_W}]"),
    ]
    for old, new in edits:
        t = replace_once(t, old, new)
    # data_dir appears in Train and Eval.
    assert t.count("data_dir: ./train_data/") == 2
    t = t.replace("data_dir: ./train_data/", f"data_dir: {DATA_DIR}")
    # max_text_length: 25 appears in NRTRHead, RecConAug and the train MultiLabelEncode.
    assert t.count("max_text_length: 25") == 3
    t = t.replace("max_text_length: 25", f"max_text_length: {MAX_TEXT_LEN}")
    header = (
        f"# Fine-tuning config: {epochs} epoch(s). Generated by scripts/make_finetune_configs.py\n"
        f"# from configs/upstream_reference/latin_PP-OCRv5_mobile_rec.yml (PaddleOCR v3.3.0).\n"
        f"# The 2-epoch and 4-epoch files differ only in Global.epoch_num and output paths.\n"
    )
    return header + t


if __name__ == "__main__":
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for n in (2, 4):
        path = OUT_DIR / f"ppocrv5_mobile_{n}epochs.yml"
        path.write_text(build(n), encoding="utf-8")
        print("wrote", path.relative_to(ROOT))
